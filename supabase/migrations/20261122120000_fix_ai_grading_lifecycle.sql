-- 1. ANSWER-LEVEL GRADING ENHANCEMENTS
-- Adds explicit grading status, method, feedback, and timestamp to user_answers
ALTER TABLE public.user_answers 
  ADD COLUMN IF NOT EXISTS grading_status TEXT DEFAULT 'pending' 
  CHECK (grading_status IN ('pending', 'in_progress', 'graded', 'failed', 'retry_pending'));

ALTER TABLE public.user_answers 
  ADD COLUMN IF NOT EXISTS grading_method TEXT 
  CHECK (grading_method IN ('deterministic_exact', 'ai'));

ALTER TABLE public.user_answers 
  ADD COLUMN IF NOT EXISTS ai_feedback TEXT;

ALTER TABLE public.user_answers 
  ADD COLUMN IF NOT EXISTS graded_at TIMESTAMPTZ;

-- Backfill existing graded rows safely
UPDATE public.user_answers ua
SET grading_status = 'graded',
    graded_at = qa.completed_at
FROM public.quiz_attempts qa
WHERE ua.attempt_id = qa.id
  AND qa.is_graded = true
  AND ua.grading_status = 'pending';

-- 2. AI OBSERVABILITY & USAGE TRACKING TABLE
-- Enables persistent tracking of provider, latency, tokens, error categories, and auditability
CREATE TABLE IF NOT EXISTS public.ai_grading_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id BIGINT REFERENCES public.quiz_attempts(id) ON DELETE CASCADE,
    answer_id BIGINT REFERENCES public.user_answers(id) ON DELETE CASCADE,
    question_id BIGINT REFERENCES public.questions(id) ON DELETE CASCADE,
    provider TEXT NOT NULL DEFAULT 'google_gemini',
    model TEXT NOT NULL DEFAULT 'gemini-2.5-flash',
    status TEXT NOT NULL CHECK (status IN ('success', 'failed', 'timeout', 'rate_limit', 'parse_error', 'blocked')),
    http_status INT,
    prompt_tokens INT,
    completion_tokens INT,
    total_tokens INT,
    latency_ms INT,
    error_message TEXT,
    error_category TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Enable RLS on ai_grading_logs
ALTER TABLE public.ai_grading_logs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Admins can view AI grading logs" ON public.ai_grading_logs;
CREATE POLICY "Admins can view AI grading logs" 
  ON public.ai_grading_logs FOR SELECT 
  USING (public.is_admin(auth.uid()));

-- Index for attempt and answer diagnostics
CREATE INDEX IF NOT EXISTS idx_ai_grading_logs_attempt ON public.ai_grading_logs(attempt_id);
CREATE INDEX IF NOT EXISTS idx_ai_grading_logs_created_at ON public.ai_grading_logs(created_at DESC);


